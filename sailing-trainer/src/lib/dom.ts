export type Child = Node | string | number | null | undefined | false | Child[];
export type Attrs = Record<string, unknown>;

/** Tiny hyperscript helper: h('div', {class: 'x', onClick: fn}, 'text', child). */
export function h<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  attrs?: Attrs | null,
  ...children: Child[]
): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag);
  if (attrs) {
    for (const [key, value] of Object.entries(attrs)) {
      if (value === undefined || value === null || value === false) continue;
      if (key.startsWith('on') && typeof value === 'function') {
        el.addEventListener(key.slice(2).toLowerCase(), value as EventListener);
      } else if (key === 'html') {
        // Only ever used with SVG/markup generated by this app, never user input.
        el.innerHTML = String(value);
      } else if (key === 'style' && typeof value === 'object') {
        Object.assign(el.style, value);
      } else if (key in el && key !== 'list' && key !== 'type') {
        (el as unknown as Record<string, unknown>)[key] = value;
      } else {
        el.setAttribute(key === 'className' ? 'class' : key, value === true ? '' : String(value));
      }
    }
  }
  append(el, children);
  return el;
}

export function append(parent: Node, children: Child[]): void {
  for (const c of children) {
    if (c === null || c === undefined || c === false) continue;
    if (Array.isArray(c)) append(parent, c);
    else parent.appendChild(typeof c === 'object' ? c : document.createTextNode(String(c)));
  }
}

export function clear(el: Element): void {
  while (el.firstChild) el.removeChild(el.firstChild);
}

/** English text that can be hidden globally (tap to reveal). */
export function en(text: string, extraClass = ''): HTMLSpanElement {
  const s = h('span', { class: `en ${extraClass}`.trim(), lang: 'en', title: 'English' }, text);
  s.addEventListener('click', (e) => {
    if (document.body.classList.contains('en-hidden')) {
      e.stopPropagation();
      s.classList.toggle('revealed');
    }
  });
  return s;
}

export function shuffle<T>(arr: readonly T[], rnd: () => number = Math.random): T[] {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export function pick<T>(arr: readonly T[], rnd: () => number = Math.random): T {
  return arr[Math.floor(rnd() * arr.length)];
}

/** Choose `n` distinct items from `pool` that are not `exclude`. */
export function distractors<T>(pool: readonly T[], exclude: T, n: number, same?: (a: T, b: T) => boolean): T[] {
  const eq = same ?? ((a, b) => a === b);
  return shuffle(pool.filter((p) => !eq(p, exclude))).slice(0, n);
}
